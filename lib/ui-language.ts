export function translate(locale: Locale, message: string, ...values: (string | number)[]) {
  const localized = locale === "en-US" && Object.hasOwn(english, message) ? english[message] : message;
  return values.length ? localized.replace(/\{(\d+)\}/g, (placeholder, index: string) => String(values[Number(index)] ?? placeholder)) : localized;
}
